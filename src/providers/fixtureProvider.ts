import type { PentadNormal, PentadNormalProvider } from '../engine/climatology.ts';
import type { HistoricalObservation, HistoricalObservationProvider } from '../engine/reportOrchestrator.ts';

/**
 * In-memory provider for Pentad Climatological Normals.
 */
export class InMemoryPentadNormalProvider implements PentadNormalProvider {
  private data = new Map<string, PentadNormal>();

  constructor(normals: PentadNormal[] = []) {
    for (const n of normals) {
      this.data.set(`${n.station}_${n.pentad}`, n);
    }
  }

  getNormal(stationId: string, pentad: string): PentadNormal | null {
    return this.data.get(`${stationId}_${pentad}`) ?? null;
  }
}

/**
 * In-memory provider for Historical Baseline Observations (24h comparison).
 */
export class InMemoryHistoricalProvider implements HistoricalObservationProvider {
  private data = new Map<string, HistoricalObservation>();
  private fallbackByStation = new Map<string, HistoricalObservation>();

  constructor(observations: HistoricalObservation[] = []) {
    for (const obs of observations) {
      this.data.set(`${obs.stationId}_${obs.date}`, obs);
      if (!this.fallbackByStation.has(obs.stationId)) {
        this.fallbackByStation.set(obs.stationId, obs);
      }
    }
  }

  getObservation(stationId: string, date: string): HistoricalObservation | null {
    const cleanId = stationId.trim();
    const cleanDate = date.trim();
    return this.data.get(`${cleanId}_${cleanDate}`) ?? this.fallbackByStation.get(cleanId) ?? null;
  }
}

